package gateway

import (
	"encoding/json"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/protoadapt"
)

// jsonMessage satisfies the proto.Message return type grpc-gateway v2 requires
// while keeping the JSON wire format of the original message. The server's
// marshalers use encoding/json, and the bare protoadapt wrapper around a
// gogo-generated message has no exported fields, so it would serialize as {}.
type jsonMessage struct {
	proto.Message
	orig any
}

func (m jsonMessage) MarshalJSON() ([]byte, error) {
	return json.Marshal(m.orig)
}

// MessageV2Of bridges a message generated by gogo/protobuf (which predates
// protoreflect) to grpc-gateway v2's proto.Message response type. For
// protoc-gen-go messages the protoadapt conversion is a no-op and the JSON
// output is unchanged. Called from generated .pb.gw.go code (injected by the
// protoc rule in the Makefile).
func MessageV2Of(m protoadapt.MessageV1) proto.Message {
	return jsonMessage{Message: protoadapt.MessageV2Of(m), orig: m}
}
