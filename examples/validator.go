package validation

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/santhosh-tekuri/jsonschema/v6"
	"github.com/santhosh-tekuri/jsonschema/v6/kind"
	"sigs.k8s.io/yaml"
)

// validKinds are the workflow resource kinds schema.json's generator
// (hack/api/jsonschema/main.go) defines a discriminated
// "io.argoproj.workflow.v1alpha1.<kind>" definition for. Checking a
// document's "kind" against this list before compiling that definition
// means an unrecognised kind (including one containing characters like "%"
// or "~" that would otherwise break the JSON pointer lookup below) is
// reported as a per-file failure instead of either escaping the walk below
// or matching some unrelated internal definition of the same name.
var validKinds = []string{
	"ClusterWorkflowTemplate",
	"CronWorkflow",
	"Workflow",
	"WorkflowEventBinding",
	"WorkflowTemplate",
}

func ValidateArgoYamlRecursively(fromPath string, skipFileNames []string) (map[string][]string, error) {
	// schema.json is generated by hack/api/jsonschema/main.go, which is
	// what defines the per-kind "io.argoproj.workflow.v1alpha1.<kind>"
	// definitions compiled by name below.
	schemaBytes, err := os.ReadFile("../api/jsonschema/schema.json")
	if err != nil {
		return nil, err
	}

	schemaDoc, err := jsonschema.UnmarshalJSON(bytes.NewReader(schemaBytes))
	if err != nil {
		return nil, err
	}

	c := jsonschema.NewCompiler()
	// api/jsonschema/schema.json declares draft 2020-12, for which format
	// assertion is off by default; gojsonschema (the library this replaced)
	// always asserted format, so this restores that behaviour for the one
	// format either library recognizes, date-time.
	c.AssertFormat()
	if err := c.AddResource("schema.json", schemaDoc); err != nil {
		return nil, err
	}

	failed := map[string][]string{}

	err = filepath.Walk(fromPath, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if slices.Contains(skipFileNames, info.Name()) {
			return filepath.SkipDir
		}
		if info.IsDir() {
			return nil
		}
		if filepath.Ext(path) != ".yaml" {
			return nil
		}
		yamlBytes, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			return err
		}

		var doc any
		if err := yaml.Unmarshal(yamlBytes, &doc); err != nil {
			return err
		}

		docMap, _ := doc.(map[string]any)
		kindStr, _ := docMap["kind"].(string)
		if !slices.Contains(validKinds, kindStr) {
			failed[path] = []string{fmt.Sprintf("unknown kind %q", kindStr)}
			return nil
		}

		schema, compileErr := c.Compile("schema.json#/definitions/io.argoproj.workflow.v1alpha1." + kindStr)
		if compileErr != nil {
			return compileErr
		}

		if validationErr := schema.Validate(doc); validationErr != nil {
			ve, ok := validationErr.(*jsonschema.ValidationError)
			if !ok {
				return validationErr
			}
			if errs := realErrors(doc, ve.DetailedOutput()); len(errs) > 0 {
				errorDescriptions := make([]string, 0, len(errs))
				for _, e := range errs {
					loc := e.InstanceLocation
					if loc == "" {
						loc = "(root)"
					}
					errorDescriptions = append(errorDescriptions, fmt.Sprintf("%s in %s", e.Error, loc))
				}
				failed[path] = errorDescriptions
			}
		}
		return nil
	})

	if err != nil {
		return nil, err
	}

	return failed, nil
}

// realErrors flattens a jsonschema.OutputUnit tree down to the field-level
// leaves that aren't the accepted mismatch below. Compiling the document's
// own "kind" definition directly means every remaining error already
// belongs to the document, so no oneOf-branch filtering is needed here.
func realErrors(doc any, u *jsonschema.OutputUnit) []*jsonschema.OutputUnit {
	if u.Error != nil {
		if isAcceptedTypeMismatch(doc, u) {
			return nil
		}
		return []*jsonschema.OutputUnit{u}
	}
	var errs []*jsonschema.OutputUnit
	for i := range u.Errors {
		errs = append(errs, realErrors(doc, &u.Errors[i])...)
	}
	return errs
}

// isAcceptedTypeMismatch reports whether u is the one known, accepted
// mismatch between the schema and the examples: httpGet.port and
// podDisruptionBudget.minAvailable are given as YAML integers even though
// the schema (mirroring the Kubernetes swagger) requires a string, because
// swagger 2.0 cannot express "string or integer" for a single field. Only
// integral values are tolerated; a non-integral number at these locations is
// still a genuine mismatch.
func isAcceptedTypeMismatch(doc any, u *jsonschema.OutputUnit) bool {
	if !isHttpGetPortOrMinAvailable(u.InstanceLocation) {
		return false
	}
	typeErr, ok := u.Error.Kind.(*kind.Type)
	if !ok || typeErr.Got != "number" || !slices.Contains(typeErr.Want, "string") {
		return false
	}
	val, ok := jsonPointerValue(doc, u.InstanceLocation)
	if !ok {
		return false
	}
	switch num := val.(type) {
	case float64:
		return num == math.Trunc(num)
	case json.Number:
		_, err := num.Int64()
		return err == nil
	default:
		return false
	}
}

// isHttpGetPortOrMinAvailable reports whether loc is a JSON pointer to a
// httpGet.port or podDisruptionBudget.minAvailable field.
func isHttpGetPortOrMinAvailable(loc string) bool {
	return strings.HasSuffix(loc, "/httpGet/port") || strings.HasSuffix(loc, "/podDisruptionBudget/minAvailable")
}

// jsonPointerValue resolves the RFC 6901 JSON pointer used by
// OutputUnit.InstanceLocation against the decoded document.
func jsonPointerValue(doc any, pointer string) (any, bool) {
	if pointer == "" {
		return doc, true
	}
	cur := doc
	for _, tok := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		tok = strings.ReplaceAll(strings.ReplaceAll(tok, "~1", "/"), "~0", "~")
		switch v := cur.(type) {
		case map[string]any:
			val, ok := v[tok]
			if !ok {
				return nil, false
			}
			cur = val
		case []any:
			idx, err := strconv.Atoi(tok)
			if err != nil || idx < 0 || idx >= len(v) {
				return nil, false
			}
			cur = v[idx]
		default:
			return nil, false
		}
	}
	return cur, true
}
