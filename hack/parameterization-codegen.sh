#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
# Same generator version as the repository's native CRD pipeline.
TOOL="${CONTROLLER_GEN:-$(go env GOPATH)/bin/controller-gen}"
"$TOOL" --version | grep -q 'v0.18.0' || { echo 'controller-gen v0.18.0 required' >&2; exit 1; }
# Native make codegen owns deepcopy/client/informer generation for ./pkg/apis.
# Do not run a second object generator here and alternate generated output.
"$TOOL" paths=./pkg/apis/parameterization/... crd:maxDescLen=0,generateEmbeddedObjectMeta=true output:crd:dir=manifests/parameterization/crds
python3 - <<'PY'
from pathlib import Path
import yaml
root=Path('manifests/parameterization');docs=[]
for file in sorted((root/'crds').glob('*.yaml')):
 obj=yaml.safe_load(file.read_text());obj['metadata']['labels']={'app.kubernetes.io/part-of':'argo-parameterization-experiment'}
 file.write_text('# Code generated by hack/parameterization-codegen.sh. DO NOT EDIT.\n'+yaml.safe_dump(obj,sort_keys=False))
 docs.append(obj)
(root/'crds.yaml').write_text('# Code generated by hack/parameterization-codegen.sh. DO NOT EDIT.\n'+yaml.safe_dump_all(docs,sort_keys=False))
PY
